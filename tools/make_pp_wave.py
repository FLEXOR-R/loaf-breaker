#!/usr/bin/env python3
"""PRESS PLAY's picture (app/ui/pp_wave.h): a bar of what LOAF BREAKER sounds like with APACHE and the kick on steps 1
and 9 through SUB DRIVE, as the CDJ view sees it (lows, mids, highs and peak a column, 15 columns a step), so the start
screen can draw it. Plays tools/ppwave/scenario.txt in the host simulator (./build.sh --host first), takes the last
whole bar from the CDJ view's ring and writes the table. Run it again only to change the picture.

    python3 tools/make_pp_wave.py
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOST = os.path.join(ROOT, "app/build/host/choppah_host")


def main():
    tmp = tempfile.mkdtemp()
    dump = os.path.join(tmp, "scope.txt")
    scen = os.path.join(tmp, "scenario.txt")
    with open(os.path.join(ROOT, "tools/ppwave/scenario.txt")) as f:
        open(scen, "w").write(f.read().replace("$OUT", dump))
    subprocess.run([HOST, scen, tmp], check=True, stdout=subprocess.DEVNULL)
    lines = open(dump).read().split("\n")
    w, step, phase = (int(x) for x in lines[0].split())
    ring = [tuple(int(v) for v in l.split()) for l in lines[1:] if l.strip()]
    n = len(ring)
    start = w - int(round((step + phase / 1000.0) * 15)) - 240   # the last whole bar before the playhead's
    cols = [ring[(start + i) % n] for i in range(240)]
    peak = max(c[3] for c in cols) or 1
    out = ["/* SPDX-License-Identifier: MPL-2.0 */",
           "/* LOAF BREAKER: PRESS PLAY's picture, a bar of APACHE with the kick on 1 and 9 through SUB DRIVE as the CDJ view",
           " * sees it: lows, mids, highs, peak (0..255, the peak at its loudest 255) a column. Generated by",
           " * tools/make_pp_wave.py from the host simulator: do not edit. */",
           "static const uint8_t PP_WAVE[240][4] = {"]
    row = []
    for c in cols:
        row.append("{%d,%d,%d,%d}" % (c[0], c[1], c[2], min(255, c[3] * 255 // peak)))
        if len(row) == 8:
            out.append("    " + ", ".join(row) + ",")
            row = []
    out.append("};")
    open(os.path.join(ROOT, "app/ui/pp_wave.h"), "w").write("\n".join(out) + "\n")
    print("wrote app/ui/pp_wave.h (bar from column %d)" % start)


if __name__ == "__main__":
    sys.exit(main())
