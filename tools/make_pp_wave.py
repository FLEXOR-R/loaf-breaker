#!/usr/bin/env python3
"""PRESS PLAY's picture (app/ui/pp_wave.h): two bars (32 steps) of THEWORM with the kick DISTORTO on every beat, drawn as
the CDJ view would (lows, mids, highs and peak a column, 15 columns a step), for the start screen. Not the exact mix: the
break and the kick are played apart in the host simulator (tools/ppwave/break.txt, kick.txt; ./build.sh --host first)
and laid one over the other, the break a little lower so its hits read, the kick in the lows' red over it, each hit drawn falling away
within a step (DISTORTO clips flat: its own tail would fill the bar). Run it again only to change the picture.

    python3 tools/make_pp_wave.py
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOST = os.path.join(ROOT, "app/build/host/loaf-breaker_host")


def bar(name):
    """two whole bars in a row from the CDJ view's ring, after playing tools/ppwave/NAME.txt: the last whole bar before
    the playhead at each of its two dumps, a bar (1412 ms at 170 BPM) apart"""
    tmp = tempfile.mkdtemp()
    dumps = [os.path.join(tmp, "scope%d.txt" % i) for i in (1, 2)]
    scen = os.path.join(tmp, "scenario.txt")
    with open(os.path.join(ROOT, "tools/ppwave", name + ".txt")) as f:
        open(scen, "w").write(f.read().replace("$OUT2", dumps[1]).replace("$OUT", dumps[0]))
    subprocess.run([HOST, scen, tmp], check=True, stdout=subprocess.DEVNULL)
    cols = []
    for d in dumps:
        lines = open(d).read().split("\n")
        w, step, phase = (int(x) for x in lines[0].split())
        ring = [tuple(int(v) for v in l.split()) for l in lines[1:] if l.strip()]
        start = w - int(round((step + phase / 1000.0) * 15)) - 240
        cols += [ring[(start + i) % len(ring)] for i in range(240)]
    return cols


def main():
    import math
    brk, kick = bar("break"), bar("kick")
    bpk = sorted(c[3] for c in brk)[int(480 * 0.97)] or 1   # (the break's hits, not one lone peak, at the top)
    kpk = max(c[3] for c in kick) or 1
    out = ["/* SPDX-License-Identifier: MPL-2.0 */",
           "/* LOAF BREAKER: PRESS PLAY's picture, two bars (32 steps) of THEWORM with the kick DISTORTO on every beat, as the CDJ view would",
           " * draw it (the break and the kick played apart and laid together, the kick in the lows' red): lows, mids,",
           " * highs, peak (0..255) a column. Generated by tools/make_pp_wave.py from the host simulator: do not edit. */",
           "static const uint8_t PP_WAVE[240][4] = {"]
    row = []
    cols = []
    for x, (b, k) in enumerate(zip(brk, kick)):
        bh = min(1.0, b[3] / bpk) * 0.8            # the break: up to 80 % of the height
        since = x % 60                             # (the kick's hits: steps 1, 5, 9, 13, 60 columns apart)
        kh = k[3] / kpk * math.exp(-since / 16.0)  # the kick: each hit, falling away over a step and a half
        h = max(bh, kh)
        m = max(b[0], b[1], b[2]) or 1
        br = [b[0] / m, b[1] / m, b[2] / m]        # the break's colour, its loudest band at 1
        kw = kh / (kh + bh) if kh + bh else 0.0    # how much of the column is the kick
        col = [br[0] * (1 - kw) + 1.0 * kw, br[1] * (1 - kw) + 0.12 * kw, br[2] * (1 - kw) + 0.05 * kw]
        cols.append((col, min(1.0, h)))
    for x in range(240):                           # 32 steps on the screen's width: two columns in one
        (c1, h1), (c2, h2) = cols[2 * x], cols[2 * x + 1]
        col, h = (c1, h1) if h1 >= h2 else (c2, h2)
        row.append("{%d,%d,%d,%d}" % (round(col[0] * 255), round(col[1] * 255), round(col[2] * 255), round(h * 255)))
        if len(row) == 8:
            out.append("    " + ", ".join(row) + ",")
            row = []
    out.append("};")
    open(os.path.join(ROOT, "app/ui/pp_wave.h"), "w").write("\n".join(out) + "\n")
    print("wrote app/ui/pp_wave.h")


if __name__ == "__main__":
    sys.exit(main())
