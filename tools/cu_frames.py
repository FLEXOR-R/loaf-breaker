"""The player's breaks (LOAF BREAKER 0.9.32, CHOPPAH 1.4's custom break, PRD A-54h) as the BREAKS page sends them:
WAVs made into a bank exactly as the built-in breaks are (tools/prep_breaks.py), and the SysEx frames that write it
into a zone (ui/main.c app_sysex; app.c CU_ZB). For the tests:
    python3 tools/cu_frames.py [--zone Z] FILE.wav BPM NAME [...] > build/custom.txt   a host scenario that uploads it
    python3 tools/cu_frames.py --bank [--zone Z] FILE.wav BPM NAME [...] OUT.bin       just the bank image"""
import argparse
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import prep_breaks as pb  # noqa: E402

CHUNK = 512
ZONES = (0x93000, 0xE5000)                          # app.c CU_ZB: where each zone's bank starts
DATA_LO, DATA_HI = 0x97000, 0xE0000                 # the data area; outside it, the XDATA windows


def at_fix(img, zone):
    """no sector of an XDATA window with "AT" at 0xF06 (the update loader's record mark, plat.h): 'A' 0x41 made
    0x40 there (an ADPCM nibble 1 -> 0, the same step index after), the CRC made again (the page does the same)"""
    b, base = bytearray(img), ZONES[zone]
    for s in range(base, base + len(b), 4096):
        o = s + 0xF06 - base
        if (s < DATA_LO or s >= DATA_HI) and b[o:o + 2] == b"AT":
            b[o] = 0x40
    struct.pack_into("<I", b, 12, zlib.crc32(b[16:]))
    return bytes(b)


def pack7(b):
    out = bytearray()
    for i in range(0, len(b), 7):
        g = b[i:i + 7]
        out.append(sum(((v >> 7) & 1) << j for j, v in enumerate(g)))
        out += bytes(v & 0x7F for v in g)
    return bytes(out)


def frame(cmd, data=b""):
    return bytes([0xF0, 0x7D, 0x43, 0x48, cmd]) + pack7(data) + bytes([0xF7])


def bank(*specs):
    """specs: (wav, bpm, name) each; LOAF BREAKER 0.9.32: a bank of one or more (the player's breaks)"""
    if len(specs) == 3 and not isinstance(specs[0], tuple):
        specs = (specs,)
    args = argparse.Namespace(bars=2, slices=16, break_slices=16, rate=22050, transients=True, loudness=-16.0,
                              name_prefix="")
    return pb.build_bank([pb.prepare(f"{w}:{b}:2:{n}", args) for w, b, n in specs])


def frames(img, zone=0):
    u32 = lambda v: v.to_bytes(4, "little")  # noqa: E731
    z = zone << 4
    yield "begin", frame(z | 2, u32(len(img)))
    for off in range(16, len(img), CHUNK):
        yield "data", frame(z | 3, u32(off) + img[off:off + CHUNK])
    yield "commit", frame(z | 4, img[:16])


def hexs(f):
    return " ".join(f"{v:02X}" for v in f)


if __name__ == "__main__":
    a = sys.argv[1:]
    only = a[:1] == ["--bank"]
    a = a[1:] if only else a
    zone = 0
    if a[:1] == ["--zone"]:
        zone, a = int(a[1]), a[2:]
    if only:                                        # --bank [--zone Z] WAV BPM NAME [WAV BPM NAME ...] OUT.bin
        Path(a[-1]).write_bytes(at_fix(bank(*[(a[i], float(a[i + 1]), a[i + 2]) for i in range(0, len(a) - 1, 3)]),
                                       zone))
        raise SystemExit
    specs = [(a[i], float(a[i + 1]), a[i + 2]) for i in range(0, len(a) - len(a) % 3, 3)]   # WAV BPM NAME ...
    img = at_fix(bank(*specs), zone)
    print(f"# generated by tools/cu_frames.py: {', '.join(n for _, _, n in specs)} ({len(img)} B) into zone {zone}")
    for kind, f in frames(img, zone):
        print(f"sysex {hexs(f)}")
        print("wait 20" if kind == "data" else "wait 200")
