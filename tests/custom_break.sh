#!/bin/sh
# SPDX-License-Identifier: MPL-2.0
# The player's breaks (LOAF BREAKER 0.9.32, CHOPPAH 1.4's custom break, several, in two places) end to end in the host
# simulator: two WAVs made into one bank as the BREAKS page makes it (tools/cu_frames.py, prep_breaks.py's way),
# uploaded over SysEx into the first place, a third into the second; checked, breaks 10 to 12 after the bank's nine (the one sent played),
# kept through a reboot, each place read back byte for byte, an update record's mark refused, deleted one place at a
# time; then a bank where a 0.9.32 TEST put it (0x97000) read, and gone once the first place is written.
# Needs ./build.sh --host first.
#   tests/custom_break.sh
set -e
cd "$(dirname "$0")/.."
O=app/build/custom
mkdir -p "$O"
W=breaks/classics/rotary_connection_life_could.wav
W2=breaks/classics/lightnin_rod_sport.wav
W3=breaks/classics/james_brown_funky_drummer.wav
python3 tools/cu_frames.py --bank "$W" 99.81 "LIFE COULD" "$W2" 120.69 "SPORT" "$O/bank.bin"
python3 tools/cu_frames.py --bank --zone 1 "$W3" 99.81 "DRUMMER" "$O/bank1.bin"
N=$(wc -c < "$O/bank.bin")
N1=$(wc -c < "$O/bank1.bin")
reads() {                                # reads ZONE SIZE: READ frames for the whole bank
    off=0
    while [ $off -lt $2 ]; do
        echo "sysex $(python3 -c "
import sys; sys.path.insert(0,'tools'); import cu_frames as c
print(c.hexs(c.frame($1 << 4 | 5, ($off).to_bytes(4,'little') + (256).to_bytes(4,'little'))))")"
        off=$((off + 256))
    done
}
{
cat <<'S'
# (generated by tests/custom_break.sh)
wait 4200
expect n_user 0
expect n_breaks 9
sysex_out
sysex F0 7D 43 48 01 F7
wait 50
expect_sysex F0 7D 43 48 41 00 00 02 00 00 02 00 23 00 00 00 00 30 02 00 00 00 00 00 00 00 17 00 00 00 00 70 01 00 00 00 00 00 F7
tap PLAY
wait 300
sysex F0 7D 43 48 02 03 55 4F 00 00 F7
wait 100
expect_sysex F0 7D 43 48 42 01 F7
tap PLAY
wait 300
S
python3 tools/cu_frames.py "$W" 99.81 "LIFE COULD" "$W2" 120.69 "SPORT" | tail -n +2
cat <<'S'
expect n_user 2
expect n_breaks 11
expect brk 9
S
python3 tools/cu_frames.py --zone 1 "$W3" 99.81 "DRUMMER" | tail -n +2
cat <<'S'
expect n_user 3
expect n_breaks 12
expect brk 11
shot cu_loaded.png
tap PLAY
wait 1500
expect peak_db_min -30
tap PLAY
wait 300
reboot
wait 4200
expect n_user 3
expect n_breaks 12
S
reads 0 "$N"
reads 1 "$N1"
python3 - <<'P'
import sys; sys.path.insert(0, 'tools'); import cu_frames as c
img = bytearray(4096)                    # (an update record's mark at 0xF06 of the second place's first sector)
img[0xF06:0xF08] = b"AT"
print("sysex " + c.hexs(c.frame(0x12, (8192).to_bytes(4, "little"))))
print("wait 200")
print("sysex " + c.hexs(c.frame(0x13, (0xF00).to_bytes(4, "little") + bytes(img[0xF00:0xF10]))))
print("wait 100")
print("expect_sysex F0 7D 43 48 53 02 F7")
P
cat <<'S'
expect data.0xE5F06 255
wait 100
sysex_log off
expect n_user 2
expect n_breaks 11
sysex F0 7D 43 48 06 F7
wait 300
expect n_user 0
expect n_breaks 9
S
echo "data $PWD/$O/bank.bin 0x97000"
cat <<'S'
reboot
wait 4200
expect n_user 2
expect n_breaks 11
sysex F0 7D 43 48 06 F7
wait 300
expect n_user 0
expect data.0x97000 255
S
echo "data $PWD/$O/bank.bin 0x97000"
cat <<'S'
reboot
wait 4200
expect n_user 2
S
python3 tools/cu_frames.py --zone 0 "$W3" 99.81 "DRUMMER" | tail -n +2
cat <<'S'
expect n_user 1
expect n_breaks 10
expect brk 9
S
} > "$O/custom.txt"
sed -i "s|^sysex_out\$|sysex_log $PWD/$O/out.syx\nsysex_out|" "$O/custom.txt"
rm -f "$O/out.syx"
app/build/host/loaf-breaker_host "$O/custom.txt" app/build/scenarios > "$O/run.log" 2>&1 || { grep -E "FAIL|host:" "$O/run.log"; exit 1; }
grep -E "FAIL|host:" "$O/run.log" || true
python3 - "$O/out.syx" "$O/bank.bin" "$O/bank1.bin" <<'P'
import sys
raw = open(sys.argv[1], "rb").read()
for z, path in ((0, sys.argv[2]), (1, sys.argv[3])):
    img = open(path, "rb").read()
    got = bytearray(len(img))
    seen = 0
    for f in raw.split(b"\xf0")[1:]:
        f = f.split(b"\xf7")[0]
        if f[:4] != bytes([0x7D, 0x43, 0x48, 0x45 | z << 4]) or f[4] != 0:
            continue
        p, u = f[5:], bytearray()
        for i in range(0, len(p), 8):
            hi = p[i]
            u += bytes(p[i + j] | ((hi >> (j - 1)) & 1) << 7 for j in range(1, min(8, len(p) - i)))
        off = int.from_bytes(u[:4], "little")
        d = u[4:]
        n = min(len(d), len(img) - off)
        got[off:off + n] = d[:n]
        seen += 1
    assert seen and bytes(got) == img, f"place {z}: read back differs ({seen} frames)"
    print(f"custom_break: place {z}: {len(img)} B uploaded, loaded, kept at power-on, read back the same in {seen} frames")
print("custom_break: an update record's mark refused, each place deleted; a 0.9.32 TEST's bank read, gone once rewritten")
P
